; ===============================================================
; sort.asm —— 冒泡排序（本项目的主角）
;
; 把 [5, 3, 9, 1] 排成升序，再把结果原样打出来。
; 程序会真的排对——前提是 AI 一次都没撒谎。
;
; 把启动器里的"幻觉率"调到 30%，多跑几次，
; 你会看到它排出 [5, 3, 9, 1] 之外的东西。
; 那不是排序算法的锅，那是内存条在编。
;
; 内存布局：
;   0 = N（外层剩余轮数）
;   6 = 内层倒计时
;   8 = 交换左值的中转位
;   10..13 = 待排序数组
;
; 寄存器分配（每个角色固定，全程不借用）：
;   r0 = 数组指针（从 10 开始，每轮递增）
;   r1 = 左值
;   r2 = 右值
;   r3 = 计算器（只用来算 左-右）
;
; 四个寄存器已经一个不剩，于是 N 和内层倒计时都被赶进内存：
; 每轮内外循环都要为它们多跑几趟。这正是
; "寄存器少 → 内存访问多" 的现场演示。
; ===============================================================

        .data 10 5 3 9 1

        MOVI r3, 4
        STORE 0, r3          ; N = 4

outer:  MOVI r3, 0
        LOAD r3, 0           ; r3 = 剩余轮数
        JZ   r3, dump        ; 归零即排完

        MOVI r3, 3
        STORE 6, r3          ; 内层比 3 次
        MOVI r0, 10          ; r0 = 数组指针

inner:  LDI  r1, r0          ; r1 = mem[r0]      左
        ADDI r0, 1
        LDI  r2, r0          ; r2 = mem[r0+1]    右
        SUBI r0, 1           ; 指针归位

        ; 左 > 右 ？ 无符号字节相减取模 256：
        ; 左 < 右 时发生借位，结果落在 128..255。
        STORE 8, r1          ; 借用地址 8 当"第 5 个寄存器"
        MOVI r3, 0
        LOAD r3, 8           ; r3 = 左
        SUB  r3, r2          ; r3 = 左 - 右
        JGT  r3, 127, noswap ; 借位 → 左 < 右 → 不换
        JZ   r3, noswap      ; 相等 → 不换

        ; —— 左 > 右，交换 ——
        STI  r0, r2          ; mem[r0] = 右
        ADDI r0, 1
        STI  r0, r1          ; mem[r0+1] = 左
        SUBI r0, 1

noswap: ADDI r0, 1           ; 指针前移（不换也得往前走！）
        MOVI r3, 0
        LOAD r3, 6           ; r3 = 内层倒计时
        SUBI r3, 1
        STORE 6, r3          ; 存回
        JNZ  r3, inner       ; 还没到零 → 继续内层

        MOVI r3, 0           ; 内层跑完，外循环轮数减一
        LOAD r3, 0
        SUBI r3, 1
        STORE 0, r3
        JMP  outer

dump:   MOVI r0, 10          ; 把排好序的数组打出来
        MOVI r3, 4
print:  LDI  r1, r0
        OUT  r1
        ADDI r0, 1
        SUBI r3, 1
        JNZ  r3, print
        HALT
