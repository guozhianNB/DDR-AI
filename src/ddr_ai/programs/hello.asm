; ===============================================================
; hello.asm —— 最小客户程序："HI"
; 先把两个字节写进内存，再读回来打到屏幕。
; 总共 4 次内存访问，但每一次都要经过总线和 AI。
; 想看整活的完整效果，请从 sort.asm 开始。
; ===============================================================

        MOVI r0, 72         ; 'H'
        STORE 64, r0
        MOVI r0, 73         ; 'I'
        STORE 65, r0

        MOVI r0, 64         ; r0 = 读指针
        MOVI r3, 2          ; r3 = 倒计时

next:   LDI  r1, r0         ; 从内存取一个字节（间接寻址）
        OUT  r1             ; 打到屏幕
        ADDI r0, 1          ; 指针前移
        SUBI r3, 1          ; 倒计时减一
        JNZ  r3, next       ; 还没到零就继续

        HALT
